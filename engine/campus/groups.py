"""Index every face of CKPT17-CLEAN.obj by its SketchUp group path (spec 2026-10-03, P0 task 8).

SketchUp OBJ export group line format:
    g Mesh<id> <InnermostComponentOrGroup> [<InnerGroup> ... <OuterGroup>] Model

Each token on the `g` line represents a level in the SketchUp hierarchy:
- Mesh<N>: the mesh chunk identifier generated by SketchUp
- InnermostComponentOrGroup: innermost component or group ancestor (often a Minecraft/LittleTiles tile type, or a named group)
- Group hierarchy: zero or more group/component ancestor names (innermost to outermost)
- Model: root model container

Three real example lines from CKPT17-CLEAN.obj:
1. 7: g Mesh1 minecraft_quartz_block_side__1 BRS_3rd_floor_obj Model
2. 302327: g Mesh967 Group10 minecraft_quartz_block_top__1_4 Eds_11th_Floor_obj Model
3. 2214652: g Mesh8296 BRIDGE BRIDGE_ZONE Model
"""
from __future__ import annotations

import argparse
import collections
import json
import os
from pathlib import Path
import re
import shlex
import tempfile
from typing import Any, Iterable

AUTO = re.compile(
    r"^(Group|Mesh|Component)\d*$|^(minecraft|littletiles|kirosblocks|mumi|Color|Material)[_A-Za-z0-9]*$",
    re.I,
)

KEY = re.compile(
    r"floor|side_?walk|stair|bridge|roof|pathway|ground",
    re.I,
)


def parse_group_line(line: str) -> tuple[str, ...]:
    """Parse a single Wavefront OBJ `g` line into its group path tuple.

    Preserves the fuller path tokens[1:-1] between Mesh<N> and Model.
    """
    line = line.strip()
    if not line.startswith("g"):
        return ()
    body = line[1:].strip()
    if not body:
        return ()
    if '"' in body:
        tokens = shlex.split(body)
    else:
        tokens = body.split()
    if not tokens:
        return ()
    # SketchUp export format: Mesh<N> [Hierarchy ...] Model
    if tokens and tokens[-1] == "Model":
        return tuple(tokens[1:-1])
    return tuple(tokens)


def parse_group_paths(sample: Path | str | Iterable[str]) -> list[tuple[str, ...]]:
    """Return, per face in file order, the path tuple.

    Faces occurring before any `g` line receive the empty tuple `()`.
    Raises FileNotFoundError for a missing path (Path or str).
    """
    cur_path: tuple[str, ...] = ()
    out: list[tuple[str, ...]] = []

    def _iter_lines() -> Iterable[str]:
        if isinstance(sample, Path):
            if not sample.is_file():
                raise FileNotFoundError(f"File not found: {sample}")
            with open(sample, "r", encoding="utf-8", errors="replace") as fh:
                for line in fh:
                    yield line
            return
        if isinstance(sample, str):
            if "\n" in sample:
                for line in sample.splitlines():
                    yield line
                return
            p = Path(sample)
            if not p.is_file():
                raise FileNotFoundError(f"File not found: {sample}")
            with open(p, "r", encoding="utf-8", errors="replace") as fh:
                for line in fh:
                    yield line
            return
        for line in sample:
            yield line

    for line in _iter_lines():
        if line.startswith("g ") or line.startswith("g\t") or line == "g\n":
            cur_path = parse_group_line(line)
        elif line.startswith("f ") or line.startswith("f\t"):
            out.append(cur_path)

    return out


def split_name(path: tuple[str, ...], skip_owner_slot: bool = False) -> str:
    """Follow the naming rule to map a group path tuple to a split name.

    skip_owner_slot defaults to False (note 1's naming tests need that) while
    index_by_split passes True, so split_name(path) and idx["split"] differ for
    30 of 1,346 paths. Consumers read idx["split"].

    - if skip_owner_slot is True, skips the slot after Mesh# (matching the owner's split_named.py);
    - ignore automatic names (Group###, Mesh###, minecraft_*, littletiles_*, etc.);
    - take the outermost group whose name contains floor, side_walk, stair, bridge,
      roof, pathway or ground; if there is none, take the outermost named group;
    - replace spaces and dots with `_`;
    - an empty path or only automatic names without fallback returns 'unnamed'.
    """
    if not path:
        return "unnamed"
    if skip_owner_slot:
        path = path[1:]
        if not path:
            return "unnamed"
    named = [a for a in path if not AUTO.match(a)]
    if not named:
        raw = path[-1] if path else "unnamed"
    else:
        kw = [a for a in named if KEY.search(a)]
        raw = kw[-1] if kw else named[-1]

    cleaned = re.sub(r"[ .]", "_", raw)
    cleaned = re.sub(r"[^A-Za-z0-9_.-]", "_", cleaned)[:100] or "unnamed"
    return cleaned


def index_by_split(
    index: Any,
    skip_owner_slot: bool = True,
) -> dict[str, int]:
    """Group faces by split name and count them as dict[str, int]."""
    if isinstance(index, dict):
        if "split" in index and isinstance(index["split"], dict):
            return {
                str(k): int(v.get("tris", 0) if isinstance(v, dict) else v)
                for k, v in index["split"].items()
            }
        return {
            str(k): int(v.get("tris", 0) if isinstance(v, dict) else v)
            for k, v in index.items()
        }

    counts: dict[str, int] = collections.defaultdict(int)
    for p in index:
        sname = split_name(p, skip_owner_slot=skip_owner_slot)
        counts[sname] += 1

    return dict(counts)


def build_group_index(obj_path: Path | str) -> dict:
    """Build the group index data structure for an OBJ file.

    Output format:
    - paths: list of path tuples (stored as list of lists/tuples);
    - faces: run-length list of `[path_id, first_face, count]` in clean-OBJ face order;
    - split: `{split_name: {"tris": n, "paths": [path_id, ...]}}`.
    """
    path_to_id: dict[tuple[str, ...], int] = {}
    paths_list: list[tuple[str, ...]] = []
    faces_rle: list[list[int]] = []

    cur_path: tuple[str, ...] = ()
    cur_path_id: int | None = None
    last_path_id: int | None = None
    current_first_face = 0
    current_count = 0
    face_idx = 0

    with open(obj_path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            if line.startswith("g ") or line.startswith("g\t") or line == "g\n":
                cur_path = parse_group_line(line)
                if cur_path not in path_to_id:
                    path_to_id[cur_path] = len(paths_list)
                    paths_list.append(cur_path)
                cur_path_id = path_to_id[cur_path]
            elif line.startswith("f ") or line.startswith("f\t"):
                if cur_path_id is None:
                    if () not in path_to_id:
                        path_to_id[()] = len(paths_list)
                        paths_list.append(())
                    cur_path_id = path_to_id[()]
                if cur_path_id == last_path_id:
                    current_count += 1
                else:
                    if last_path_id is not None:
                        faces_rle.append([last_path_id, current_first_face, current_count])
                    last_path_id = cur_path_id
                    current_first_face = face_idx
                    current_count = 1
                face_idx += 1

    if last_path_id is not None:
        faces_rle.append([last_path_id, current_first_face, current_count])

    split_dict: dict[str, dict] = {}
    for path_id, path_tuple in enumerate(paths_list):
        sname = split_name(path_tuple, skip_owner_slot=True)
        if sname not in split_dict:
            split_dict[sname] = {"tris": 0, "paths": []}
        split_dict[sname]["paths"].append(path_id)

    for path_id, _first_face, count in faces_rle:
        sname = split_name(paths_list[path_id], skip_owner_slot=True)
        split_dict[sname]["tris"] += count

    return {
        "paths": [list(p) for p in paths_list],
        "faces": faces_rle,
        "split": split_dict,
    }


def write_group_index_atomic(out_path: Path, data: dict) -> None:
    """Atomically write index data to out_path as JSON."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".group_index-", suffix=".json.tmp", dir=out_path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump(data, fh, indent=1)
        os.replace(tmp, out_path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def cmd_campus_index(source_json_path: Path, out_path: Path) -> dict:
    """Load source.json, index the clean OBJ, write out_path, and return index dict."""
    with open(source_json_path, "r", encoding="utf-8") as fh:
        source_data = json.load(fh)
    clean_obj_path = Path(source_data["clean_obj"]["path"])
    if not clean_obj_path.exists():
        raise FileNotFoundError(f"Clean OBJ not found: {clean_obj_path}")

    index_data = build_group_index(clean_obj_path)
    write_group_index_atomic(out_path, index_data)
    return index_data


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Index every face of clean OBJ by group path")
    parser.add_argument("--source", type=Path, default=Path("data/campus/source.json"),
                        help="the source.json file from campus-freeze")
    parser.add_argument("--out", type=Path, default=Path("data/campus/group_index.json"),
                        help="output group_index.json")
    args = parser.parse_args(argv)
    cmd_campus_index(args.source, args.out)
    return 0


if __name__ == "__main__":
    main()
