CHAR_W = 5
CHAR_H = 7
SPACING = 1


def text_rects(text, x0, y0, cell):
    """Yield (x, y, w, h) rectangles, in the same units as `cell`.

    x0, y0 is the lower-left of the first glyph. Text reads left to right,
    rows top to bottom. Unknown characters render as a space.
    """
    text = text.upper()
    pen_x = x0
    for ch in text:
        rows = GLYPHS.get(ch, GLYPHS[" "])
        for r, row in enumerate(rows):
            y = y0 + (CHAR_H - 1 - r) * cell
            c = 0
            while c < CHAR_W:
                if row[c] == "1":
                    run = 1
                    while c + run < CHAR_W and row[c + run] == "1":
                        run += 1
                    yield (pen_x + c * cell, y, run * cell, cell)
                    c += run
                else:
                    c += 1
        pen_x += (CHAR_W + SPACING) * cell


def text_width(text, cell):
    return len(text) * (CHAR_W + SPACING) * cell
